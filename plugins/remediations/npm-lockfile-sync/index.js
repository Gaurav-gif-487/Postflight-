"use strict";
const fs = require("fs");
const path = require("path");

// Reference RemediationProvider (docs/remediation-api.md), shipped as a
// worked example the same way plugins/lang-* is a worked example of the
// plugin API. Targets exactly the evidence
// src/analyzers/dependencyChange.js emits when a manifest changed but no
// matching lockfile did: `dependency/lockfile-not-updated@<file>`.
//
// This never runs a package manager itself - postflight providers are
// read-only by contract (see docs/remediation-api.md). It only inspects
// the working tree to figure out *which* lockfile command applies (e.g.
// yarn vs npm vs pnpm), then suggests that command for a human (or a
// future explicit "apply" step) to run.

const EVIDENCE_PREFIX = "dependency/lockfile-not-updated@";

// package.json can be regenerated by more than one package manager; which
// one is "correct" for a given repo is whichever lockfile already exists
// there, not a global default. Ecosystems with exactly one standard tool
// (Cargo, Bundler, Go modules) don't need this disambiguation.
function npmCommandFor(manifestDir, repoRoot) {
  const abs = (name) => fs.existsSync(path.join(repoRoot, manifestDir, name));
  if (abs("yarn.lock")) return "yarn install";
  if (abs("pnpm-lock.yaml")) return "pnpm install";
  if (abs("bun.lock") || abs("bun.lockb")) return "bun install";
  return "npm install";
}

function suggestionFor(file, repoRoot) {
  const dir = path.dirname(file);
  const prefixCmd = (cmd) => (dir === "." ? cmd : `cd ${dir} && ${cmd}`);
  const base = path.basename(file);

  switch (base) {
    case "package.json":
      return { kind: "command", commands: [prefixCmd(npmCommandFor(dir, repoRoot))] };
    case "Cargo.toml":
      return { kind: "command", commands: [prefixCmd("cargo update")] };
    case "Gemfile":
      return { kind: "command", commands: [prefixCmd("bundle install")] };
    case "go.mod":
      return { kind: "command", commands: [prefixCmd("go mod tidy")] };
    case "requirements.txt":
    case "pyproject.toml":
      // Python has no single standard lock command - which one applies
      // depends on which tool the project already uses, which this
      // provider has no reliable way to detect from the manifest alone.
      return {
        kind: "manual",
        summary:
          "Regenerate the lockfile with whichever tool this project uses " +
          "(e.g. `poetry lock` for Poetry, `pip-compile` for pip-tools, " +
          "`pipenv lock` for Pipenv) - no single command applies to every requirements.txt/pyproject.toml project.",
      };
    default:
      return null;
  }
}

module.exports = {
  metadata: { name: "npm-lockfile-sync", version: "0.1.0", apiVersion: 1 },
  canRemediate(ev) {
    return ev.category === "dependency" && ev.id.startsWith(EVIDENCE_PREFIX);
  },
  remediate(ev, ctx) {
    const file = ev.id.slice(EVIDENCE_PREFIX.length);
    const suggestion = suggestionFor(file, ctx.repoRoot);
    if (!suggestion) return null;
    return {
      summary: suggestion.summary || `Regenerate the lockfile for ${file}`,
      kind: suggestion.kind,
      commands: suggestion.commands,
    };
  },
  // exported for direct unit testing
  npmCommandFor,
  suggestionFor,
};
