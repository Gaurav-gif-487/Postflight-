"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { toSarif, toGithubAnnotations } = require("../src/formats");

function finding(overrides = {}) {
  return {
    rule: "secret-aws-key",
    severity: "high",
    category: "secret",
    label: "Possible AWS access key",
    file: "src/x.js",
    snippet: "AKIA...",
    ...overrides,
  };
}

test("toSarif: produces a well-formed SARIF 2.1.0 document", () => {
  const sarif = toSarif({ findings: [finding()], scoreResult: { confidence: 60, status: "REVIEW_REQUIRED" } });
  assert.equal(sarif.version, "2.1.0");
  assert.equal(sarif.runs[0].tool.driver.name, "postflight");
  assert.equal(sarif.runs[0].results.length, 1);
  assert.equal(sarif.runs[0].results[0].ruleId, "secret-aws-key");
  assert.equal(sarif.runs[0].results[0].level, "error");
});

test("toSarif: maps severities to the correct SARIF levels", () => {
  const sarif = toSarif({
    findings: [finding({ rule: "a", severity: "high" }), finding({ rule: "b", severity: "medium" }), finding({ rule: "c", severity: "low" })],
    scoreResult: { confidence: 50, status: "REVIEW_REQUIRED" },
  });
  const levels = sarif.runs[0].results.map((r) => r.level);
  assert.deepEqual(levels, ["error", "warning", "note"]);
});

test("toSarif: a finding with no file has no locations", () => {
  const sarif = toSarif({ findings: [finding({ file: null })], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" } });
  assert.deepEqual(sarif.runs[0].results[0].locations, []);
});

test("toSarif: deduplicates rule ids in the rules list", () => {
  const sarif = toSarif({
    findings: [finding(), finding()],
    scoreResult: { confidence: 50, status: "REVIEW_REQUIRED" },
  });
  assert.equal(sarif.runs[0].tool.driver.rules.length, 1);
});

test("toSarif: a plain v1 finding (no evidence detail) gets no properties bag on its result", () => {
  const sarif = toSarif({ findings: [finding()], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" } });
  assert.equal(sarif.runs[0].results[0].properties, undefined);
});

test("toSarif: an evidence-schema finding's confounders/provenance/data surface in the result's properties bag", () => {
  const sarif = toSarif({
    findings: [
      finding({
        rule: "dependency-added",
        confounders: ["lockfile may be regenerated by CI"],
        provenance: { method: "observed", source: "package.json", ref: "HEAD" },
        data: { name: "left-pad", version: "1.0.0" },
      }),
    ],
    scoreResult: { confidence: 80, status: "SAFE_TO_MERGE" },
  });
  const props = sarif.runs[0].results[0].properties;
  assert.ok(props, "expected a properties bag");
  assert.deepEqual(props.confounders, ["lockfile may be regenerated by CI"]);
  assert.deepEqual(props.provenance, { method: "observed", source: "package.json", ref: "HEAD" });
  assert.deepEqual(props.data, { name: "left-pad", version: "1.0.0" });
});

test("toSarif: only carries the evidence-detail fields that are actually present", () => {
  const sarif = toSarif({
    findings: [finding({ rule: "dependency-added", data: { name: "left-pad" } })],
    scoreResult: { confidence: 80, status: "SAFE_TO_MERGE" },
  });
  const props = sarif.runs[0].results[0].properties;
  assert.deepEqual(Object.keys(props), ["data"]);
});

test("toSarif: run-level properties include verified when scoreResult carries it", () => {
  const withVerified = toSarif({ findings: [], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE", verified: true } });
  assert.equal(withVerified.runs[0].properties.verified, true);

  const withoutVerified = toSarif({ findings: [], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" } });
  assert.equal("verified" in withoutVerified.runs[0].properties, false);
});

test("toSarif: informationUri reflects the resolved repoUrl when provided", () => {
  const sarif = toSarif({
    findings: [],
    scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" },
    repoUrl: "https://github.com/acme/widgets",
  });
  assert.equal(sarif.runs[0].tool.driver.informationUri, "https://github.com/acme/widgets");
});

test("toSarif: omits informationUri entirely (no fabricated placeholder) when repoUrl isn't resolvable", () => {
  const sarif = toSarif({ findings: [], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" } });
  assert.equal("informationUri" in sarif.runs[0].tool.driver, false);
});

test("toSarif: run-level properties include the task result when --task/--task-file ran", () => {
  const taskResult = {
    task: "Add OAuth",
    requirements: [{ id: "T-001", requirement: "OAuth callback exists", status: "INCONCLUSIVE", evidence: [], detail: "..." }],
    counts: { SATISFIED: 0, UNSATISFIED: 0, INCONCLUSIVE: 1 },
  };
  const sarif = toSarif({ findings: [], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" }, taskResult });
  assert.deepEqual(sarif.runs[0].properties.task, taskResult);
});

test("toSarif: omits the task property entirely when --task wasn't passed", () => {
  const sarif = toSarif({ findings: [], scoreResult: { confidence: 90, status: "SAFE_TO_MERGE" } });
  assert.equal("task" in sarif.runs[0].properties, false);
});

test("toGithubAnnotations: formats a workflow command line per finding", () => {
  const out = toGithubAnnotations({ findings: [finding()] });
  assert.match(out, /^::error file=src\/x\.js,title=postflight:secret-aws-key::/);
  assert.match(out, /Possible AWS access key: AKIA\.\.\./);
});

test("toGithubAnnotations: maps severities to error/warning/notice", () => {
  const out = toGithubAnnotations({
    findings: [finding({ rule: "a", severity: "high" }), finding({ rule: "b", severity: "medium" }), finding({ rule: "c", severity: "low" })],
  });
  const lines = out.split("\n");
  assert.match(lines[0], /^::error /);
  assert.match(lines[1], /^::warning /);
  assert.match(lines[2], /^::notice /);
});

test("toGithubAnnotations: omits the file= segment when a finding has no file", () => {
  const out = toGithubAnnotations({ findings: [finding({ file: null })] });
  assert.doesNotMatch(out, /file=/);
});

test("toGithubAnnotations: empty findings produces an empty string", () => {
  assert.equal(toGithubAnnotations({ findings: [] }), "");
});
